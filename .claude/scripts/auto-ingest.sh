#!/usr/bin/env bash

set -euo pipefail

export PATH="$HOME/.local/bin:/opt/homebrew/bin:/opt/homebrew/share/google-cloud-sdk/bin:$PATH"

if [[ -z "${NODE_EXTRA_CA_CERTS:-}" && -n "${BRAIN_CA_BUNDLE:-}" && -f "$BRAIN_CA_BUNDLE" ]]; then
    export NODE_EXTRA_CA_CERTS="$BRAIN_CA_BUNDLE"
fi

VAULT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPTS_DIR="${VAULT_DIR}/.claude/scripts"
LOG_DIR="${VAULT_DIR}/wiki/logs"
LOG_FILE="${LOG_DIR}/auto-ingest.log"
STATUS_FILE="${VAULT_DIR}/outputs/.ingest-status.json"
BRIEFING_FILE="${VAULT_DIR}/outputs/.session-briefing.md"
PENDING_FILE="${VAULT_DIR}/outputs/.ingest-pending"
AUTH_SKIP_STREAK_FILE="${VAULT_DIR}/outputs/.ingest-auth-skip-streak"
LOCK_DIR="${BRAIN_LOCK_DIR:-/tmp/brain-auto-ingest.lock}"
MAX_SESSIONS="${MAX_SESSIONS:-5}"
MAX_LOG_LINES=1000
STALE_LOCK_SECONDS=1800

DRY_RUN=false
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=true

mkdir -p "$LOG_DIR"

log() {
    local ts
    ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    echo "[${ts}] $*" | tee -a "$LOG_FILE"
}

write_status() {
    local processed="${1:-0}" skipped="${2:-0}" failed="${3:-0}" pending="${4:-0}" error="${5:-}" force_unhealthy="${6:-false}"
    local ts
    ts=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

    local total_summaries
    total_summaries=$(find "${VAULT_DIR}/wiki/summaries" -name "*.md" 2>/dev/null | wc -l | tr -d ' ')

    local streak_file="${VAULT_DIR}/outputs/.ingest-streak-failures"
    local streak=0
    if [[ "$failed" -gt 0 ]]; then
        streak=$(cat "$streak_file" 2>/dev/null || echo "0")
        streak=$((streak + 1))
        echo "$streak" > "$streak_file"
    else
        rm -f "$streak_file"
    fi

    local auth_skip_streak
    auth_skip_streak=$(cat "$AUTH_SKIP_STREAK_FILE" 2>/dev/null || echo "0")

    local healthy=true
    if [[ "$streak" -ge 3 || "$auth_skip_streak" -ge 3 || "$force_unhealthy" == "true" \
          || "$SCAN_UNKNOWN_TOTAL" -gt 0 || "$GAUGE_SELFCHECK_OK" != true ]]; then
        healthy=false
    fi

    if [[ -z "$error" ]]; then
        if [[ "$GAUGE_SELFCHECK_OK" != true ]]; then
            error="gauge_selfcheck_failed"
        elif [[ "$SCAN_UNKNOWN_TOTAL" -gt 0 ]]; then
            error="unrecognised_status_present"
        fi
    fi

    local tmp_status="${STATUS_FILE}.tmp"
    cat > "$tmp_status" <<EOJSON
{
  "last_run": "${ts}",
  "processed": ${processed},
  "skipped": ${skipped},
  "failed": ${failed},
  "pending": ${pending},
  "pending_synthetic": ${SCAN_PENDING_SYNTHETIC},
  "session_files_total": ${SCAN_TOTAL},
  "status_histogram": ${SCAN_HISTOGRAM_JSON},
  "unknown_status": ${SCAN_UNKNOWN_JSON},
  "unknown_status_count": ${SCAN_UNKNOWN_TOTAL},
  "gauge_selfcheck_ok": ${GAUGE_SELFCHECK_OK},
  "total_summaries": ${total_summaries},
  "streak_failures": ${streak},
  "auth_skip_streak": ${auth_skip_streak},
  "healthy": ${healthy},
  "last_error": "${error}",
  "dry_run": ${DRY_RUN}
}
EOJSON
    mv "$tmp_status" "$STATUS_FILE"
}

acquire_lock() {
    if mkdir "$LOCK_DIR" 2>/dev/null; then
        echo $$ > "${LOCK_DIR}/pid"
        trap 'rm -rf "$LOCK_DIR"' EXIT
        return 0
    fi

    if [[ -d "$LOCK_DIR" ]]; then
        local lock_pid lock_age
        lock_pid=$(cat "${LOCK_DIR}/pid" 2>/dev/null || echo "0")
        lock_age=$(( $(date +%s) - $(stat -f %m "$LOCK_DIR" 2>/dev/null || echo "0") ))

        if ! kill -0 "$lock_pid" 2>/dev/null || [[ "$lock_age" -gt "$STALE_LOCK_SECONDS" ]]; then
            log "Reclaiming lock (PID ${lock_pid} $(kill -0 "$lock_pid" 2>/dev/null && echo 'alive but stale' || echo 'dead'), age ${lock_age}s)"
            rm -rf "$LOCK_DIR"
            if mkdir "$LOCK_DIR" 2>/dev/null; then
                echo $$ > "${LOCK_DIR}/pid"
                trap 'rm -rf "$LOCK_DIR"' EXIT
                return 0
            fi
        fi
    fi

    log "Another auto-ingest is running (lock held). Exiting."
    return 1
}

check_environment() {
    if [[ -n "${PI_CODING_AGENT:-}" ]]; then
        if ! command -v pi &>/dev/null; then
            log "ERROR: 'pi' not found in PATH"
            write_status 0 0 1 0 "pi not in PATH"
            return 1
        fi
    else
        if ! command -v claude &>/dev/null; then
            log "ERROR: 'claude' not found in PATH"
            write_status 0 0 1 0 "claude not in PATH"
            return 1
        fi
    fi

}

generate_briefing() {
    local briefing_tmp="${BRIEFING_FILE}.tmp"
    local cutoff
    cutoff=$(date -v-48H +%s 2>/dev/null || date -d '48 hours ago' +%s 2>/dev/null || echo "0")

    cat > "$briefing_tmp" <<'EOF'
# Recent Session Activity

_Auto-generated by auto-ingest.sh. Read at session start for cross-session context._

EOF

    local found=0
    for summary in "${VAULT_DIR}/wiki/summaries"/*.md; do
        [[ -f "$summary" ]] || continue

        local mtime
        mtime=$(stat -f %m "$summary" 2>/dev/null || stat -c %Y "$summary" 2>/dev/null || echo "0")
        [[ "$mtime" -lt "$cutoff" ]] && continue

        found=$((found + 1))
        local title project first_para
        title=$(awk '/^# /{print substr($0,3); exit}' "$summary")
        project=$(awk '/^project:/{print $2; exit}' "$summary")

        first_para=$(awk '
            /^## Summary/{found=1; next}
            found && /^$/{if(seen) exit; next}
            found && /^#/{exit}
            found{seen=1; print}
        ' "$summary" | head -3)

        echo "## [${project:-unknown}] ${title:-untitled}" >> "$briefing_tmp"
        echo "" >> "$briefing_tmp"
        echo "${first_para:-_No summary available_}" >> "$briefing_tmp"
        echo "" >> "$briefing_tmp"
    done

    if [[ "$found" -eq 0 ]]; then
        echo "_No summaries from the last 48 hours._" >> "$briefing_tmp"
    fi

    echo "" >> "$briefing_tmp"
    echo "_Generated: $(date -u +"%Y-%m-%dT%H:%M:%SZ") | Summaries found: ${found}_" >> "$briefing_tmp"

    mv "$briefing_tmp" "$BRIEFING_FILE"
}

rotate_logs() {
    for logfile in "${LOG_DIR}"/*.log; do
        [[ -f "$logfile" ]] || continue
        [[ "$logfile" == *-[0-9][0-9][0-9][0-9]-[0-9][0-9].log ]] && continue
        local line_count
        line_count=$(wc -l < "$logfile" | tr -d ' ')
        if [[ "$line_count" -gt "$MAX_LOG_LINES" ]]; then
            local base ext archive
            base=$(basename "$logfile" .log)
            archive="${LOG_DIR}/${base}-$(date +%Y-%m).log"
            head -n "$((line_count - MAX_LOG_LINES / 2))" "$logfile" >> "$archive"
            tail -n "$((MAX_LOG_LINES / 2))" "$logfile" > "${logfile}.tmp"
            mv "${logfile}.tmp" "$logfile"
            log "Rotated ${logfile} (${line_count} lines)"
        fi
    done
}

TERMINAL_STATUSES="promoted skipped orphaned"
KNOWN_STATUSES="promoted skipped orphaned captured draft"

SCAN_TOTAL=0
SCAN_PENDING=0
SCAN_PENDING_SYNTHETIC=0
SCAN_UNKNOWN_TOTAL=0
SCAN_UNKNOWN_JSON="{}"
SCAN_HISTOGRAM_JSON="{}"
SCAN_HISTOGRAM=""
GAUGE_SELFCHECK_OK=true

scan_statuses() {
    local dir="${1:-}"
    [[ -z "$dir" ]] && dir="${VAULT_DIR}/outputs/session-summaries"

    SCAN_TOTAL=0; SCAN_PENDING=0; SCAN_PENDING_SYNTHETIC=0; SCAN_UNKNOWN_TOTAL=0
    SCAN_UNKNOWN_JSON="{}"; SCAN_HISTOGRAM_JSON="{}"; SCAN_HISTOGRAM=""

    local files=()
    local nullglob_was_set=false
    shopt -q nullglob && nullglob_was_set=true
    shopt -s nullglob
    files=( "$dir"/*.md )
    $nullglob_was_set || shopt -u nullglob
    [[ ${#files[@]} -eq 0 ]] && return 0

    SCAN_HISTOGRAM=$(awk '
        FNR==1 { nfiles++; seen=0; syn=0 }
        !seen && /^synthetic:[[:space:]]*true[[:space:]]*$/ { syn=1 }
        !seen && /^status:/ {
            v=$0; sub(/^status:[[:space:]]*/,"",v); sub(/[[:space:]]+$/,"",v)
            if (v=="") v="(empty)"
            c[v]++; if (syn) s[v]++
            seen=1; nextfile
        }
        END {
            n=0
            for (k in c) { printf "%s\t%d\t%d\n", k, c[k], s[k]+0; n+=c[k] }
            if (nfiles > n) printf "(missing)\t%d\t0\n", nfiles-n
            printf "TOTALFILES\t%d\t0\n", nfiles+0
        }
    ' "${files[@]}")

    local label count syncount safe hist_pairs="" unknown_pairs=""
    while IFS=$'\t' read -r label count syncount; do
        [[ -n "${label:-}" ]] || continue
        if [[ "$label" == "TOTALFILES" ]]; then SCAN_TOTAL="$count"; continue; fi

        safe=$(printf '%s' "$label" | tr -cd 'A-Za-z0-9_.()-' | cut -c1-40)
        [[ -z "$safe" ]] && safe="(unprintable)"
        hist_pairs+="${hist_pairs:+, }\"${safe}\": ${count}"

        case " ${TERMINAL_STATUSES} " in
            *" ${label} "*) : ;;
            *) SCAN_PENDING=$((SCAN_PENDING + count - ${syncount:-0}))
               SCAN_PENDING_SYNTHETIC=$((SCAN_PENDING_SYNTHETIC + ${syncount:-0})) ;;
        esac

        case " ${KNOWN_STATUSES} " in
            *" ${label} "*) : ;;
            *) SCAN_UNKNOWN_TOTAL=$((SCAN_UNKNOWN_TOTAL + count))
               unknown_pairs+="${unknown_pairs:+, }\"${safe}\": ${count}" ;;
        esac
    done <<< "$SCAN_HISTOGRAM"

    SCAN_HISTOGRAM_JSON="{${hist_pairs}}"
    SCAN_UNKNOWN_JSON="{${unknown_pairs}}"
    return 0
}

selfcheck_gauge() {
    local fx rc=0
    fx=$(mktemp -d "${TMPDIR:-/tmp}/brain-gauge-selfcheck.XXXXXX") || return 1
    _mkfx() {
        printf -- '---\nid: %s\ntype: session_summary\nstatus: %s\n---\n\n# Session: %s\n' \
            "$1" "$2" "$1" > "${fx}/2026-01-01-$1.md"
    }
    _mkfxsyn() {
        printf -- '---\nid: %s\ntype: session_summary\nsynthetic: true\nstatus: %s\n---\n\n# Session: %s\n' \
            "$1" "$2" "$1" > "${fx}/2026-01-01-$1.md"
    }
    _mkfx aaaaaaaa promoted; _mkfx bbbbbbbb skipped;  _mkfx cccccccc captured
    _mkfx dddddddd draft;    _mkfx eeeeeeee orphaned; _mkfx ffffffff banana
    _mkfxsyn 99999999 captured

    local s_total="$SCAN_TOTAL" s_pend="$SCAN_PENDING" s_unk="$SCAN_UNKNOWN_TOTAL"
    local s_psyn="$SCAN_PENDING_SYNTHETIC"
    local s_ujson="$SCAN_UNKNOWN_JSON" s_hjson="$SCAN_HISTOGRAM_JSON" s_hist="$SCAN_HISTOGRAM"

    scan_statuses "$fx"

    [[ "$SCAN_TOTAL"         -eq 7 ]] || { log "SELFCHECK FAIL: total=${SCAN_TOTAL} != 7"; rc=1; }
    [[ "$SCAN_PENDING"       -eq 3 ]] || { log "SELFCHECK FAIL: pending=${SCAN_PENDING} != 3 (unknown status not counted as backlog)"; rc=1; }
    [[ "$SCAN_PENDING_SYNTHETIC" -eq 1 ]] || { log "SELFCHECK FAIL: pending_synthetic=${SCAN_PENDING_SYNTHETIC} != 1 (harness backlog not split out)"; rc=1; }
    [[ "$SCAN_UNKNOWN_TOTAL" -eq 1 ]] || { log "SELFCHECK FAIL: unknown=${SCAN_UNKNOWN_TOTAL} != 1"; rc=1; }
    [[ "$SCAN_UNKNOWN_JSON" == '{"banana": 1}' ]] || { log "SELFCHECK FAIL: unknown_status=${SCAN_UNKNOWN_JSON}"; rc=1; }

    SCAN_TOTAL="$s_total"; SCAN_PENDING="$s_pend"; SCAN_UNKNOWN_TOTAL="$s_unk"
    SCAN_PENDING_SYNTHETIC="$s_psyn"
    SCAN_UNKNOWN_JSON="$s_ujson"; SCAN_HISTOGRAM_JSON="$s_hjson"; SCAN_HISTOGRAM="$s_hist"
    rm -rf "$fx"; unset -f _mkfx _mkfxsyn
    return $rc
}

if [[ "${1:-}" == "--scan" ]]; then
    scan_statuses "${2:-}"
    printf '%s\n' "$SCAN_HISTOGRAM"
    echo "PENDING=${SCAN_PENDING} PENDING_SYNTHETIC=${SCAN_PENDING_SYNTHETIC} UNKNOWN=${SCAN_UNKNOWN_TOTAL} TOTAL=${SCAN_TOTAL}"
    echo "HISTOGRAM_JSON=${SCAN_HISTOGRAM_JSON}"
    echo "UNKNOWN_JSON=${SCAN_UNKNOWN_JSON}"
    exit 0
fi

if [[ "${1:-}" == "--selfcheck" ]]; then
    if selfcheck_gauge; then echo "gauge selfcheck: PASS"; exit 0
    else echo "gauge selfcheck: FAIL"; exit 1; fi
fi


acquire_lock || exit 0
check_environment || exit 1

if selfcheck_gauge; then
    GAUGE_SELFCHECK_OK=true
else
    GAUGE_SELFCHECK_OK=false
    log "ALERT: gauge selfcheck FAILED — status accounting is not trustworthy this cycle."
fi

scan_statuses
pending_count="$SCAN_PENDING"
if [[ "$SCAN_UNKNOWN_TOTAL" -gt 0 ]]; then
    log "ALERT: ${SCAN_UNKNOWN_TOTAL} session summaries carry an unrecognised status: ${SCAN_UNKNOWN_JSON}"
fi
route_base_url="${ANTHROPIC_BASE_URL:-}"
if [[ -n "$route_base_url" ]] && ! curl -s -o /dev/null --max-time 5 "$route_base_url"; then
    auth_skip_streak=$(cat "$AUTH_SKIP_STREAK_FILE" 2>/dev/null || echo "0")
    auth_skip_streak=$((auth_skip_streak + 1))
    echo "$auth_skip_streak" > "$AUTH_SKIP_STREAK_FILE"

    if [[ "$auth_skip_streak" -ge 3 ]]; then
        log "ALERT: Anthropic route ${route_base_url} unreachable for ${auth_skip_streak} consecutive cycles — ingest STALLED. Fix: check proxy / endpoint connectivity. Confirm with: echo hi | claude -p"
    else
        log "SKIP: Anthropic route ${route_base_url} unreachable. Will retry next cycle."
    fi
    write_status 0 0 0 "$pending_count" "anthropic_route_unreachable_${route_base_url}" true
    exit 0
fi

rm -f "$AUTH_SKIP_STREAK_FILE"

log "=== Auto-ingest starting ==="
$DRY_RUN && log "(dry-run mode)"

reconcile_output=$(python3 "${SCRIPTS_DIR}/reconcile-drafts.py" $($DRY_RUN && echo "--dry-run") 2>&1) || true
echo "$reconcile_output" | tee -a "$LOG_FILE"

discover_output=$(python3 "${SCRIPTS_DIR}/discover-transcripts.py" $($DRY_RUN && echo "--dry-run") 2>&1) || true
echo "$discover_output" | tee -a "$LOG_FILE"

ingest_output=$("${SCRIPTS_DIR}/ingest-session.sh" --all --max-sessions "$MAX_SESSIONS" $($DRY_RUN && echo "--dry-run") 2>&1) || true
echo "$ingest_output" | tee -a "$LOG_FILE"

processed=$(echo "$ingest_output" | grep -oE 'Ingested: [0-9]+' | grep -oE '[0-9]+' || echo "0")
skipped=$(echo "$ingest_output" | grep -oE 'Skipped: [0-9]+' | grep -oE '[0-9]+' || echo "0")
failed=$(echo "$ingest_output" | grep -oE 'Failed: [0-9]+' | grep -oE '[0-9]+' || echo "0")

if [[ "$processed" -gt 0 ]] && ! $DRY_RUN; then
    log "Running compile-wiki.py backlinks indexes..."
    python3 "${SCRIPTS_DIR}/compile-wiki.py" backlinks indexes 2>&1 | tee -a "$LOG_FILE" || true
fi

generate_briefing

scan_statuses
pending="$SCAN_PENDING"
if [[ "$SCAN_UNKNOWN_TOTAL" -gt 0 ]]; then
    log "ALERT: ${SCAN_UNKNOWN_TOTAL} session summaries carry an unrecognised status: ${SCAN_UNKNOWN_JSON}"
fi
log "Status distribution: ${SCAN_HISTOGRAM_JSON} (backlog=${pending} of ${SCAN_TOTAL})"

status_error=""
if [[ "$failed" -gt 0 ]]; then
    fail_class=$(echo "$ingest_output" | grep -oE 'class=[a-z-]+' | tail -1 | cut -d= -f2)
    status_error="ingest_failed=${failed} class=${fail_class:-unknown} processed=${processed}"
fi
write_status "$processed" "$skipped" "$failed" "$pending" "$status_error"

rm -f "$PENDING_FILE"

rotate_logs

log "=== Auto-ingest complete (processed=${processed}, skipped=${skipped}, failed=${failed}, pending=${pending}) ==="
